#!/usr/bin/env bash
# Builds supabase/install_all.sql = every migration in order EXCEPT 0200 (launch-day grant).
# Paste the result once in the Supabase SQL Editor. Re-run this script after adding a migration.
set -euo pipefail
cd "$(dirname "$0")/.."
out=supabase/install_all.sql
{
  echo "-- ====================================================================="
  echo "-- Korea Finance Planner · ALL SaaS migrations in one file (generated by tools/build-install-sql.sh)"
  echo "-- Production (existing project): run this file once.  Staging (NEW project): run supabase_schema.sql FIRST."
  echo "-- NOT included: 20261113000200_legacy_launch_grant.sql → run it on launch day only."
  echo "-- Safe to run again (every migration is re-runnable). Check afterwards: select * from public.kfp_security_report();"
  echo "-- ====================================================================="
  for f in $(ls supabase/migrations/*.sql | sort); do
    case "$f" in *000200_legacy_launch_grant.sql) continue;; esac
    echo; echo "-- >>>>>>>>>>>>>>>>>>>> $(basename "$f")"; echo
    cat "$f"
  done
  echo; echo "-- done. Next: select * from public.kfp_security_report();"
} > "$out"
echo "wrote $out ($(wc -l < "$out") lines)"
